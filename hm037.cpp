/*4.2.4 嵌套循环 在循环体中再嵌套一层循环，解决一些实际问题
例如打印一些矩阵，横纵都有循环表达式
*/
#include <iostream>
using namespace std;
int main()
{
    //利用嵌套循环实现星图
    for(int i = 0 ; i < 10 ; i++ )
    {
        for(int i = 0 ; i < 10 ; i++ )
    {
        cout << "* " ;// 这里如果是:cout << "*" << endl;  则变为竖着输出
    }
    cout << endl;//for循环结束之后换行
    }
    return 0;
}
/*
为什么能用两个i——因为“作用域”不同
在 C++ 中，大括号 { } 就是一道“围墙”。
外面的 i：住在外层的围墙里（第 1 个 for 循环）。
里面的 i：住在内层的围墙里（第 2 个 for 循环）。
两个i实际上是两个不同变量
规则： 里面的围墙可以看见外面，但外面看不见里面。当你在内层声明了 int i，内层代码就会优先使用自己围墙里的 i，而把外面的 i 暂时“屏蔽”掉（这叫变量遮蔽，Shadowing）。

但不建议这样做，容易让自己混淆，标准写法如下：

int main()
{
    for(int i = 0 ; i < 10 ; i++ )   // 外层用 i
    {
        for(int j = 0 ; j < 10 ; j++ ) // 内层用 j
        {
            cout << "* " ;
        }
        cout << endl;
    }
    return 0;
}
内外用两个名字不同的变量
*/