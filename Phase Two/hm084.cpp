/*C++核心编程 
本阶段主要做针对C++ “面向对象” 编程技术，探讨C++中的核心和精髓
1.内存分区模型
C++程序在执行时，将内存大方向划分为4个区域（切记是内存的四大区域）
  代码区：存放函数体的二进制代码，由操作系统进行管理的（所有的英文代码和中文注释）
  全局区：存放全局变量和静态变量以及常量
  栈区：由编译器自动分配释放，存放函数的参数值，局部变量等（由编译器决定生存和死亡）（自动挡）
  堆区：由程序员分配和释放，（由程序员决定生存和死亡）（手动挡）若程序员不释放，程序结束时由操作系统回收

  内存四区的意义：
  不同区域存放的数据，赋予不同的生命周期，给我们更大的灵活编程

1.1 程序运行前
在程序编译后（翻译为电脑看得懂的二进制语言），生成了可执行程序，还未执行该程序前分为两个区域
代码区：
  存放CPU执行的机器指令（就是我写的代码）
  代码区是共享的，共享的目的是对于频繁被执行的程序，只需要在内存中有一份代码即可
  代码区是只读的，使其只读的原因是防止程序意外地修改了它的指令
全局区：
  全局变量和静态变量存放在此
  全局区还包含了常量区，字符串常量和其他常量也存放在此
  该区域的数据在程序结束后由操作系统释放
   
*/
#include <iostream>
using namespace std;

int global_var = 10;        // 全局区（已初始化）
int uninit_global_var;      // 全局区（未初始化，bss）
const char* str = "Hello";  // 全局区（常量字符串）

int main() {
    int local_var = 20;          // 栈区
    int* heap_var = new int(30); // 堆区
    static int static_var = 40;  // 全局区（静态变量）

    cout << "代码区（函数地址）: " << (void*)&main << endl;
    cout << "全局区（全局变量）: " << &global_var << endl;
    cout << "全局区（静态变量）: " << &static_var << endl;
    cout << "全局区（字符串常量）: " << (void*)str << endl;
    cout << "栈区（局部变量）: " << &local_var << endl;
    cout << "堆区（动态分配）: " << heap_var << endl;

    delete heap_var;
    return 0;
}
/*运行结果观察：
全局变量、静态变量、字符串常量的地址通常非常接近（都在全局区，也就是数据段/只读数据段）。
栈区和堆区的地址通常离得很远。
在Linux下，字符串常量的地址通常在整个虚拟地址空间的低地址（只读段），而全局变量在稍高的数据段。

*/